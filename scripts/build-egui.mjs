#!/usr/bin/env node
// Generate native/ironmaw-egui/src/tokens.rs from the resolved DTCG tokens
// (src/lib/tokens/resolved/*.tokens.json, written by build-tokens.mjs).
// The web build and the egui theme then share one source: palettes per
// edition, the type scale with its line heights, spacing, radii and sizes.
// Run via `pnpm run tokens` (chained) or directly: node scripts/build-egui.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const REM_PX = 16;
const editions = ['oxide', 'bone'];

const load = (name) => JSON.parse(readFileSync(join(root, `src/lib/tokens/resolved/${name}.tokens.json`), 'utf8'));
const constName = (key) => key.toUpperCase().replace(/[^A-Z0-9]+/g, '_');
const fieldName = (key) => key.replace(/[^a-z0-9]+/g, '_');

function hexToRgb(hex) {
  const m = /^#([0-9a-f]{6})$/i.exec(hex);
  if (!m) return null;
  const n = parseInt(m[1], 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

/** "0.75rem" | "18px" → points (f32); other units → null. */
function toPoints(value) {
  const m = /^(-?[\d.]+)(px|rem)$/.exec(String(value).trim());
  if (!m) return null;
  return m[2] === 'rem' ? Number(m[1]) * REM_PX : Number(m[1]);
}

const f32 = (n) => (Number.isInteger(n) ? `${n}.0` : String(n));

const first = load(editions[0]);
const colorKeys = Object.keys(first.color);

let out = `// GENERATED by scripts/build-egui.mjs from src/lib/tokens — do not edit by hand.
// Dimensions are egui points (1 rem = ${REM_PX} pt). Colours are sRGB.
#![allow(dead_code)]

use egui::Color32;

/// One edition's semantic colours (the same roles as the CSS custom properties).
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Palette {
${colorKeys.map((k) => `    pub ${fieldName(k)}: Color32,`).join('\n')}
}

`;

for (const ed of editions) {
  const t = load(ed);
  out += `/// The ${ed[0].toUpperCase() + ed.slice(1)} edition.\npub const ${constName(ed)}: Palette = Palette {\n`;
  for (const k of colorKeys) {
    const rgb = hexToRgb(t.color[k]);
    if (!rgb) throw new Error(`${ed}.${k}: not a 6-digit hex colour (${t.color[k]})`);
    out += `    ${fieldName(k)}: Color32::from_rgb(${rgb.join(', ')}),\n`;
  }
  out += '};\n\n';
}

// Brand anchors (identity only).
out += '/// Identity board anchors, verbatim. Components use the palettes instead.\npub mod brand {\n    use egui::Color32;\n';
for (const [k, v] of Object.entries(first.scale)) {
  if (!k.startsWith('brand-')) continue;
  out += `    pub const ${constName(k.slice(6))}: Color32 = Color32::from_rgb(${hexToRgb(v).join(', ')});\n`;
}
out += '}\n\n';

// Scale: every px/rem dimension and every unitless number we can express.
out += '/// Edition-agnostic scale.\npub mod scale {\n';
const skipped = [];
for (const [k, v] of Object.entries(first.scale)) {
  if (k.startsWith('brand-') || k.startsWith('font-') || k.startsWith('z-') || k.startsWith('shadow-')) continue;
  const pts = toPoints(v);
  if (pts !== null) {
    out += `    pub const ${constName(k)}: f32 = ${f32(pts)};\n`;
    continue;
  }
  if (/^-?[\d.]+$/.test(String(v))) {
    out += `    pub const ${constName(k)}: f32 = ${f32(Number(v))};\n`;
    continue;
  }
  const em = /^(-?[\d.]+)em$/.exec(String(v));
  if (em) {
    out += `    /// Multiply by the font size.\n    pub const ${constName(k)}_EM: f32 = ${f32(Number(em[1]))};\n`;
    continue;
  }
  skipped.push(`${k}=${v}`);
}
out += '}\n';
if (skipped.length) out += `\n// Not expressible as egui constants: ${skipped.join(', ')}\n`;

writeFileSync(join(root, 'native/ironmaw-egui/src/tokens.rs'), out);
console.log(`wrote native/ironmaw-egui/src/tokens.rs (${editions.length} palettes, ${colorKeys.length} roles)`);
