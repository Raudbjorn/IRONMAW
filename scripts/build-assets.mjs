// Brand vector → inlined module. The owner's traced SVG master
// (assets/brand/bear-mark.svg — transparent; bear-mark-charcoal.svg carries
// its own charcoal plate) is lightly cleaned (XML prolog and Inkscape
// editor attributes dropped, nothing redrawn) and embedded as a data URL so
// the Mark component works anywhere the compiled bundle does — design-sync
// previews included — without a static-asset pipeline. Gradient ids stay
// scoped because the mark is consumed through <img>, never inlined.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const src = join(root, 'assets/brand/bear-mark.svg');
const outDir = join(root, 'src/lib/assets');
mkdirSync(outDir, { recursive: true });

let svg = readFileSync(src, 'utf8')
  .replace(/^<\?xml[^>]*\?>\s*/, '')
  .replace(/\s+xmlns:inkscape="[^"]*"/, '')
  .replace(/\s+inkscape:[a-z-]+="[^"]*"/g, '')
  .replace(/\n\s*/g, ' ')
  .trim();

const vb = /viewBox="0 0 (\d+) (\d+)"/.exec(svg);
if (!vb) throw new Error('bear-mark.svg: viewBox not found');
const [, w, h] = vb;

const b64 = Buffer.from(svg, 'utf8').toString('base64');
const kb = Math.round(b64.length / 1024);

writeFileSync(
  join(outDir, 'bear-mark.ts'),
  `// GENERATED by scripts/build-assets.mjs — do not edit by hand.
// Owner-supplied Sveinbjörn bear mark (reference B1), vector master, transparent ground.
// Inkscape editor attributes stripped; paths untouched. (~${kb} KB base64)
export const BEAR_MARK_WIDTH = ${w};
export const BEAR_MARK_HEIGHT = ${h};
export const bearMark = 'data:image/svg+xml;base64,${b64}';
`
);
console.log('assets built:', kb, 'KB svg');
